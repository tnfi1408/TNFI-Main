// Helper to calculate composite TNFI Score from 7 distinct sub-factors
export function calculateTnfiScore(subScores: TnfiScoreFactorBreakdown): number {
  const score =
    subScores.financialHealth * 0.20 +
    subScores.growth * 0.15 +
    subScores.profitability * 0.15 +
    subScores.governance * 0.15 +
    subScores.marketPosition * 0.15 +
    subScores.agriStrength * 0.10 +
    subScores.risk * 0.10;
  return Number(score.toFixed(1));
}

